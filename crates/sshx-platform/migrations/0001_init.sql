-- sshx platform schema. Times are UNIX milliseconds.
--
-- Encrypted columns (suffix `_enc`) hold AES-256-GCM ciphertexts produced by
-- browsers or machines ("v1." + base64url(nonce || ciphertext)); the server
-- never holds the keys to open them.

CREATE TABLE users (
    id            TEXT PRIMARY KEY,
    username      TEXT NOT NULL UNIQUE,
    display_name  TEXT NOT NULL,
    oidc_subject  TEXT UNIQUE,           -- Entra object ID (oid) or OIDC sub
    is_admin      INTEGER NOT NULL DEFAULT 0,
    created_at    INTEGER NOT NULL,
    last_login_at INTEGER
);

CREATE TABLE web_sessions (
    token_hash TEXT PRIMARY KEY,         -- SHA-256 of the cookie value
    user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at INTEGER NOT NULL,
    expires_at INTEGER NOT NULL
);

-- Per-user key material. The vault key is derived in the browser from a
-- passphrase (Argon2id); the server only stores the salt, the parameters and
-- a verifier sealed with that key.
CREATE TABLE vaults (
    user_id         TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    salt            TEXT NOT NULL,
    kdf             TEXT NOT NULL,       -- JSON parameters
    verifier        TEXT NOT NULL,       -- sealed constant
    public_key      TEXT NOT NULL,       -- ECDH P-256 public key (JWK JSON)
    private_key_enc TEXT NOT NULL,       -- PKCS#8 private key sealed with the vault key
    created_at      INTEGER NOT NULL
);

CREATE TABLE machines (
    id           TEXT PRIMARY KEY,       -- generated by the browser (bound into AAD)
    owner_id     TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name         TEXT NOT NULL,
    kind         TEXT NOT NULL CHECK (kind IN ('personal', 'project')),
    project      TEXT,
    token_hash   TEXT NOT NULL UNIQUE,   -- SHA-256 of the bearer part of the token
    token_hint   TEXT NOT NULL,
    created_at   INTEGER NOT NULL,
    last_seen_at INTEGER
);

-- Who can open a machine's sessions, with the machine key wrapped for them:
-- scheme 'vault' (owner, sealed with the vault key) or 'ecdh' (shared member,
-- sealed for their public key).
CREATE TABLE machine_keys (
    machine_id TEXT NOT NULL REFERENCES machines(id) ON DELETE CASCADE,
    user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    scheme     TEXT NOT NULL CHECK (scheme IN ('vault', 'ecdh')),
    key_enc    TEXT NOT NULL,
    granted_by TEXT,
    created_at INTEGER NOT NULL,
    PRIMARY KEY (machine_id, user_id)
);

-- sshx sessions registered by machines.
CREATE TABLE sessions (
    name         TEXT PRIMARY KEY,       -- sshx session name (URL path)
    machine_id   TEXT NOT NULL REFERENCES machines(id) ON DELETE CASCADE,
    url          TEXT NOT NULL,          -- public sshx URL, without key
    sshx_server  TEXT NOT NULL,
    display_name TEXT NOT NULL,
    key_enc      TEXT NOT NULL,          -- sshx key sealed with the machine key
    hostname     TEXT NOT NULL DEFAULT '',
    username     TEXT NOT NULL DEFAULT '',
    os           TEXT NOT NULL DEFAULT '',
    arch         TEXT NOT NULL DEFAULT '',
    version      TEXT NOT NULL DEFAULT '',
    started_at   INTEGER NOT NULL,
    last_seen_at INTEGER NOT NULL,
    closed_at    INTEGER
);

CREATE INDEX sessions_machine ON sessions(machine_id);

CREATE TABLE terminals (
    session_name TEXT NOT NULL REFERENCES sessions(name) ON DELETE CASCADE,
    sid          INTEGER NOT NULL,
    state        TEXT NOT NULL,          -- none|idle|working|question|permission|done
    agent        TEXT,
    state_since  INTEGER,
    meta_enc     TEXT,                   -- cwd, git, process, agent detail
    created_at   INTEGER NOT NULL,
    updated_at   INTEGER NOT NULL,
    PRIMARY KEY (session_name, sid)
);

-- Per-user display preferences of terminals.
CREATE TABLE terminal_prefs (
    user_id      TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    session_name TEXT NOT NULL,
    sid          INTEGER NOT NULL,
    name_enc     TEXT,                   -- custom name, sealed with the machine key
    sort_key     REAL,
    pinned       INTEGER NOT NULL DEFAULT 0,
    bell         INTEGER NOT NULL DEFAULT 0,
    updated_at   INTEGER NOT NULL,
    PRIMARY KEY (user_id, session_name, sid)
);
